// The user guide's pictures (DR-0020): the "5-minute tour" done in the real app, one screenshot per
// step, and the shortcut table copied from the app's own shortcut list (`?`). One run per screen
// language (playwright.manual.config.ts). Output goes to apps/manual/img/<lang>/ and
// apps/manual/generated/keys-<lang>.html, which are committed.
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import type { Page } from '@playwright/test';
import { expect, test } from '@playwright/test';

import { openApp } from '../e2e/support';

test.use({ viewport: { width: 1100, height: 700 } });

const manualDirectory = new URL('../../manual/', import.meta.url);

/** The screen language of this run: the project name in playwright.manual.config.ts. */
function lang(): 'ko' | 'en' {
  return test.info().project.name === 'ko' ? 'ko' : 'en';
}

/** Saves the diagram with a margin, or the whole window. */
async function shot(page: Page, name: string, whole = false): Promise<void> {
  const directory = new URL(`img/${lang()}/`, manualDirectory);
  await mkdir(directory, { recursive: true });
  const path = fileURLToPath(new URL(`${name}.png`, directory));
  await page.waitForTimeout(250);
  if (whole) {
    await page.screenshot({ path });
    return;
  }
  const box = await page.locator('.ans-document').boundingBox();
  if (box === null) throw new Error('the document is not on the screen');
  const pad = 20;
  await page.screenshot({
    path,
    clip: {
      x: box.x - pad,
      y: box.y - pad,
      width: box.width + 2 * pad,
      height: box.height + 2 * pad,
    },
  });
}

async function type(page: Page, text: string): Promise<void> {
  await expect(page.locator('.ans-inline-editor')).toBeFocused();
  await page.keyboard.type(text);
}

test('the 5-minute tour', async ({ page }) => {
  await openApp(page);
  await shot(page, 'tour-0-screen', true);
  await shot(page, 'tour-1a-empty');
  await page.keyboard.press('Enter');
  await type(page, 'sum ← 0');
  await page.keyboard.press('Enter');
  await shot(page, 'tour-1b-done');
  for (const text of ['i ← 0', 'sum ← sum + a[i]', 'i ← i + 1']) {
    await page.keyboard.press('o');
    await type(page, text);
    await page.keyboard.press('Enter');
  }
  await shot(page, 'tour-2-more');
  await shot(page, 'tour-3a-start', true);
  await page.keyboard.press('Shift+ArrowUp');
  await shot(page, 'tour-3b-selected', true);
  await page.keyboard.press('s');
  await page.waitForTimeout(600);
  await shot(page, 'tour-3c-hint', true);
  await page.keyboard.press('w');
  await type(page, 'i < n');
  await page.keyboard.press('Enter');
  await shot(page, 'tour-3d-done', true);
  await shot(page, 'tour-3e-done');
  await page.keyboard.press('a');
  await page.keyboard.press('i');
  await type(page, 'n > 0');
  await page.keyboard.press('Enter');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await type(page, 'avg ← sum / n');
  await page.keyboard.press('Enter');
  await shot(page, 'tour-4-done');
  await shot(page, 'tour-5-screen', true);
});

test('the shortcut table', async ({ page }) => {
  await openApp(page);
  await page.keyboard.press('Shift+Slash');
  const table = page.locator('.ans-keytable');
  await expect(table).toBeVisible();
  const html = await table.evaluate((element) => element.outerHTML);
  const directory = new URL('generated/', manualDirectory);
  await mkdir(directory, { recursive: true });
  const header =
    '<!-- Generated by apps/web/manual-shots/tour.spec.ts from the app. Do not edit. -->\n';
  await writeFile(new URL(`keys-${lang()}.html`, directory), `${header}${html}\n`);
});
